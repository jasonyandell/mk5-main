"""walt/kernel/toys.py — tiny endgame subgames with enumerable exact values.

Toy roots are generated by the zeb engine itself under seeded RANDOM play
(no nets anywhere), so every play_history / team_points / current_trick is
consistent by construction; the hidden-world sets are hand-picked determinstic
subsets of the physics-exact enumeration (walt.worlds), with deliberately
non-uniform weights to catch normalization bugs. The registry covers 1-trick
and 2-trick roots, 7 decl_ids, hero declaring and defending, and world counts
1 / 3 / 12.

Exact values come from explicit enumeration: `discover_free_infosets` walks
the full support tree, `pure_profiles` enumerates ALL pure info-set
strategies of the free seats, `joint_value_matrix` prices every joint pure
profile with reference.profile_value, and `zero_sum_value` solves the
resulting matrix game exactly (LP) when the two free seats are on opposite
teams. On the same team, the exact value is the matrix max (a common-payoff
game against a pinned environment attains its optimum at a pure profile).
"""
